void displayCmd(void)
{
	Trace_Print("\r\n *********** cmd list begin ************\r\n");
	Trace_Print(" ??: help cmd \r\n");
	Trace_Print(" 00: reset mcu \r\n");
	Trace_Print(" 11: state idle \r\n");
	Trace_Print(" 22: state detect \r\n");
	Trace_Print(" 44: state clean \r\n");
	Trace_Print(" 55: state detect after clean \r\n");

	Trace_Print(" 99: auto run \r\n");

	Trace_Print("\r\n *********** cmd list end************\r\n\r\n");
}

 


void debugFunc(void)
{
	u8 ch[2];
	if (FifoLen(&UartRxFifo)<2) return;
	if (rcvTimeCount > 1) return;
	
	ch[0] = DeFifo(&UartRxFifo);
	ch[1] = DeFifo(&UartRxFifo);
	while (1)		//Çå³ýÆäËû
		{
			if (FifoLen(&UartRxFifo)>0) DeFifo(&UartRxFifo);
			else break;
		}
		
	if (ch[0] != ch[1]) return;

	autoRunFlag = 0;

	switch(ch[0])
		{
			case '?':
				displayCmd();
				autoRunFlag = 1;
				break;
			case '0':
				NVIC_SystemReset();
				autoRunFlag = 1;
				break;
			case '1':
				cleanState = state_idle;
				Trace_Print(" state goto idle \r\n");
				break;
			case '2':
				cleanState = state_detect;
				Trace_Print(" state goto detect \r\n");
				break;
			case '4':
				cleanState = state_clean;
				break;
			case '5':
				cleanState = state_detect_after_clean;	
				break;
			case '9':
				Trace_Print(" Auto run mode \r\n");
				cleanState = state_idle;
				autoRunFlag = 1;
				break;


			
			default: break;
		}

	
}




